import json,os
W=os.path.expanduser('~/work/v104/')
D=json.load(open(W+'texts_dump.json'))
FIX={
 '15:423':{' and its racehorses begins.':' and the racehorses begins.',' and its racehorses begins!':' and the racehorses begins!'},
 '36:698':{'No no, ':'No, no - thank you, ','Thank you too.':'.'},
 '27:119':{' in your hands.':' are in your hands now.',' in your care.':' are in your care now.'},
}
out=['# play-test 4 fixes (1.0.4 index), generated by ~/tools/mk_pt4.py'];miss=[]
for key,mp in FIX.items():
    v=list(D[key]);hit=set()
    for i,s in enumerate(v):
        if s in mp: v[i]=mp[s];hit.add(s)
    miss+=[(key,k) for k in mp if k not in hit]
    out.append(key+'|'+' ¦ '.join('' if s is None else s for s in v))
open(W+'seg_over/h_playtest4.txt','w',encoding='utf8').write('\n'.join(out)+'\n');print(len(out)-1,'missing',miss)
